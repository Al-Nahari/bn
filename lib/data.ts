export const generateServicesByRegion = (region: string) => {
  return services.filter((service) =>
    service.regions.includes(region)
  );
};

export const generateRelatedServices = (serviceId: string) => {
  const service = services.find((s) => s.id === serviceId);
  if (!service || !service.relatedServices) return [];
  return service.relatedServices
    .map((id) => services.find((s) => s.id === id))
    .filter(Boolean);
};

export const getServiceBySlug = (slug: string) => {
  return services.find((service) => service.slug === slug);
};

export const getHighPriorityServices = () => {
  return services.filter((service) => service.priority === 1);
};
